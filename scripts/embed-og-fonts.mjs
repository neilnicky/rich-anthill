// Inlines the OG fonts into a TS module so the share-card renderer does no
// filesystem I/O at runtime. Workers have no project files on disk: a
// readFile(process.cwd() + "/app/_og/…") resolves to /bundle/app/_og/… → ENOENT.
import { readFile, writeFile } from "node:fs/promises";

const dir = new URL("../app/_og/", import.meta.url);
const fonts = { archivo: "archivo-800.woff", martian: "martian-400.woff" };

let out = "// GENERATED by scripts/embed-og-fonts.mjs. Do not edit.\n";
for (const [name, file] of Object.entries(fonts)) {
  const b64 = (await readFile(new URL(file, dir))).toString("base64");
  out += `export const ${name}B64 = "${b64}";\n`;
}
await writeFile(new URL("fonts.generated.ts", dir), out);
console.log("Embedded OG fonts:", Object.values(fonts).join(", "));
